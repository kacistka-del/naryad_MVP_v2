const I18nContext = createContext(null);

function read(key, fallback) {
  try { return localStorage.getItem(key) || fallback; } catch { return fallback; }
}
function write(key, val) { try { localStorage.setItem(key, val); } catch {} }

export function LanguageProvider({ children }) {
  const [locale, setLocaleState] = useState(() => read("naryad_locale", "ru"));
  const [country, setCountryState] = useState(() => read("naryad_country", "RU"));
  const [currency, setCurrencyState] = useState(() => read("naryad_currency", "RUB"));

  const setLocale = (l) => { setLocaleState(l); write("naryad_locale", l); };
  const setCountry = (c) => {
    setCountryState(c);
    write("naryad_country", c);
    const cur = getCountry(c).currency;
    setCurrencyState(cur);
    write("naryad_currency", cur);
  };
  const setCurrency = (c) => { setCurrencyState(c); write("naryad_currency", c); };

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const t = useCallback((key) => {
    return (DICT[locale] && DICT[locale][key]) || DICT.ru[key] || DICT.en[key] || key;
  }, [locale]);

  const formatMoney = useCallback((amount) => fmtMoney(amount, currency, locale), [currency, locale]);

  const value = {
    locale, setLocale,
    country, setCountry,
    currency, setCurrency,
    countries: COUNTRIES,
    languages: LANGUAGES,
    cities: getCountry(country).cities,
    phonePrefix: getCountry(country).phone,
    t,
    formatMoney,
  };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    // fallback без провайдера (безопасно для страниц, где ещё не обёрнуто)
    return {
      locale: "ru", country: "RU", currency: "RUB",
      countries: COUNTRIES, languages: LANGUAGES, cities: getCountry("RU").cities, phonePrefix: "+7",
      t: (k) => DICT.ru[k] || k, formatMoney: (a) => fmtMoney(a, "RUB", "ru"),
      setLocale: () => {}, setCountry: () => {}, setCurrency: () => {},
    };
  }
  return ctx;
}